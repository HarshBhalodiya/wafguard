"""
Manufacturing event timeline API (Phase 1C).

One ordered event stream per lot or equipment: process start/end,
parameter excursions, equipment alarms, maintenance, recipe transitions,
inspection events. Events are generated by the simulator and stored in
`timeline_events`; this router serves them ordered by time with optional
event-type filtering.
"""
from typing import Optional

from fastapi import APIRouter, Depends, Query
from pymongo.database import Database

from app.api.deps import get_db
from app.database.repositories.lot_repository import LotRepository
from app.database.repositories.timeline_repository import TimelineEventRepository
from app.utils.exceptions import NotFoundError
from app.utils.responses import success

router = APIRouter()

EVENT_TYPES = [
    "PROCESS_START",
    "PROCESS_END",
    "PARAMETER_EXCURSION",
    "EQUIPMENT_ALARM",
    "MAINTENANCE",
    "RECIPE_TRANSITION",
    "INSPECTION",
]


@router.get("/lots/{lot_id}/timeline")
def get_lot_timeline(
    lot_id: str,
    event_type: Optional[str] = Query(default=None, description=f"Filter by type: {', '.join(EVENT_TYPES)}"),
    limit: int = Query(default=500, ge=1, le=2000),
    db: Database = Depends(get_db),
):
    if not LotRepository(db).get_by_lot_id(lot_id):
        raise NotFoundError(f"Lot {lot_id} was not found.")
    repo = TimelineEventRepository(db)
    events = repo.for_lot_by_type(lot_id, event_type) if event_type else repo.for_lot(lot_id, limit=limit)
    return success({"lot_id": lot_id, "count": len(events), "events": events})


@router.get("/equipment/{equipment_id}/timeline")
def get_equipment_timeline(
    equipment_id: str,
    event_type: Optional[str] = Query(default=None, description=f"Filter by type: {', '.join(EVENT_TYPES)}"),
    limit: int = Query(default=500, ge=1, le=2000),
    db: Database = Depends(get_db),
):
    repo = TimelineEventRepository(db)
    events = repo.find_many(
        {"equipment_id": equipment_id, **({"event_type": event_type} if event_type else {})},
        sort=[("ts", 1)],
        limit=limit,
    )
    return success({"equipment_id": equipment_id, "count": len(events), "events": events})
